#!/usr/bin/env python3
"""Generate rit/bs_option_data.h for parsec_blackscholes.c from a PARSEC input file.

    python3 gen_option_data.py in_4K.txt > \\
        $PITON_ROOT/piton/verif/diag/assembly/include/riscv/ariane/rit/bs_option_data.h

PARSEC's inputgen writes option i as row (i % 1000) of its 1000-entry table, so
every blackscholes input (in_4.txt ... in_10M.txt) is that table repeated. This
script keeps the first 1000 rows (all of them if the file is shorter) exactly as
blackscholes' fscanf("%f") would read them into floats, and the C program
rebuilds input i as row (i % rows). Any input size can then be run with
-gcc_args=-DNUM_OPTIONS=N.
"""
import ctypes
import sys

libc = ctypes.CDLL(None)
libc.strtof.restype = ctypes.c_float
libc.strtof.argtypes = [ctypes.c_char_p, ctypes.c_void_p]


def f32(s):
    """The float C's strtof (and fscanf %f) gives for this text."""
    return libc.strtof(s.encode(), None)


def lit(x):
    # %.9g round-trips any float exactly; C needs a '.' or exponent before 'f'
    t = "%.9g" % x
    if not any(c in t for c in ".en"):
        t += ".0"
    return t + "f"


rows = []
with open(sys.argv[1]) as fh:
    n = int(fh.readline())
    for line in fh:
        p = line.split()
        if len(p) != 9:
            continue
        rows.append(p)
        if len(rows) == 1000:
            break

print("// Generated by rit/benchmarks/blackscholes/gen_option_data.py from %s (%d options)."
      % (sys.argv[1].split("/")[-1], n))
print("// PARSEC blackscholes input rows, as fscanf(\"%f\") reads them. Input option i")
print("// of any PARSEC input size is row (i % BS_TABLE_ROWS).")
print("// Columns: s strike r divq v t type divs DGrefval  (type: 0 = call, 1 = put)")
print("#define BS_TABLE_ROWS %d" % len(rows))
print("static const struct { float s, strike, r, divq, v, t; int type; float divs, dgref; }")
print("bs_table[BS_TABLE_ROWS] = {")
for p in rows:
    vals = [lit(f32(p[i])) for i in range(6)]
    typ = "1" if p[6] == "P" else "0"
    print("  {%s, %s, %s}," % (", ".join(vals), typ, ", ".join(lit(f32(p[i])) for i in (7, 8))))
print("};")
